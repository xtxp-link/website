// Writes the logo files from src/brand/logo.mjs:
//   public/favicon.svg, public/brand/*.svg, src/styles/logo.generated.css
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { standalone, favicon, logoCss } from '../src/brand/logo.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = (p, s) => {
  mkdirSync(dirname(join(root, p)), { recursive: true });
  writeFileSync(join(root, p), s);
  console.log('wrote', p);
};
const png = (svg, size) => sharp(Buffer.from(svg), { density: 384 }).resize(size, size).png().toBuffer();

// A .ico that holds PNG images (16 and 32 px).
function ico(images) {
  const head = Buffer.alloc(6);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(images.length, 4);
  let offset = 6 + 16 * images.length;
  const entries = images.map(([size, data]) => {
    const e = Buffer.alloc(16);
    e[0] = size; e[1] = size; e.writeUInt16LE(1, 4); e.writeUInt16LE(32, 6);
    e.writeUInt32LE(data.length, 8); e.writeUInt32LE(offset, 12);
    offset += data.length;
    return e;
  });
  return Buffer.concat([head, ...entries, ...images.map(([, d]) => d)]);
}

// SVG favicon follows the browser's light/dark setting. Browsers that ignore SVG favicons get the .ico (dark chevrons,
// for light tab strips) or, on iOS, the apple-touch-icon (opaque black tile).
out('public/favicon.svg', favicon());
out('public/brand/favicon.svg', favicon());
const lightIcon = favicon({ scheme: 'light' });
const darkIcon = favicon({ scheme: 'dark' });
out('public/brand/favicon-light.svg', lightIcon);
out('public/brand/favicon-dark.svg', darkIcon);
writeFileSync(join(root, 'public/favicon.ico'), ico([[16, await png(lightIcon, 16)], [32, await png(lightIcon, 32)]]));
console.log('wrote public/favicon.ico');
writeFileSync(join(root, 'public/apple-touch-icon.png'), await png(favicon({ scheme: 'dark', size: 180, tile: '#000000' }), 180));
console.log('wrote public/apple-touch-icon.png');
out('public/brand/logo.svg', standalone({ mode: 'still', theme: 'auto' }));
out('public/brand/logo-animated.svg', standalone({ mode: 'loop', theme: 'auto' }));
out('public/brand/logo-light.svg', standalone({ mode: 'still', theme: 'light' }));
out('public/brand/logo-dark.svg', standalone({ mode: 'still', theme: 'dark' }));
out('public/brand/logo-animated-light.svg', standalone({ mode: 'loop', theme: 'light' }));
out('public/brand/logo-animated-dark.svg', standalone({ mode: 'loop', theme: 'dark' }));
out('public/brand/logo-on-blue.svg', standalone({ mode: 'still', theme: 'blue' }));
out('public/brand/logo-animated-on-blue.svg', standalone({ mode: 'loop', theme: 'blue' }));

// The site uses Starlight's theme variables, so one set of rules covers light and dark.
out(
  'src/styles/logo.generated.css',
  '/* Generated by scripts/render-logo.mjs from src/brand/logo.mjs. Do not edit. */\n' +
    '.xtxp-logo{--xl-x:var(--sl-color-white);--xl-t:#ff5436;--xl-p:#7d7d83}\n' +
    ':root[data-theme="light"] .xtxp-logo{--xl-t:#ff5436;--xl-p:#8a8a90}\n' +
    logoCss('.xtxp-logo').replace(/\}(?=[.@:])/g, '}\n') + '\n'
);
