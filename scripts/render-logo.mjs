// Writes the logo files from src/brand/logo.mjs:
//   public/favicon.svg, public/brand/*.svg, src/styles/logo.generated.css
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { standalone, favicon, logoCss } from '../src/brand/logo.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = (p, s) => {
  mkdirSync(dirname(join(root, p)), { recursive: true });
  writeFileSync(join(root, p), s);
  console.log('wrote', p);
};

out('public/favicon.svg', favicon());
out('public/brand/favicon.svg', favicon());
out('public/brand/logo.svg', standalone({ mode: 'still', theme: 'auto' }));
out('public/brand/logo-animated.svg', standalone({ mode: 'loop', theme: 'auto' }));
out('public/brand/logo-light.svg', standalone({ mode: 'still', theme: 'light' }));
out('public/brand/logo-dark.svg', standalone({ mode: 'still', theme: 'dark' }));
out('public/brand/logo-animated-light.svg', standalone({ mode: 'loop', theme: 'light' }));
out('public/brand/logo-animated-dark.svg', standalone({ mode: 'loop', theme: 'dark' }));
out('public/brand/logo-on-blue.svg', standalone({ mode: 'still', theme: 'blue' }));
out('public/brand/logo-animated-on-blue.svg', standalone({ mode: 'loop', theme: 'blue' }));

// The site uses Starlight's theme variables, so one set of rules covers light and dark.
out(
  'src/styles/logo.generated.css',
  '/* Generated by scripts/render-logo.mjs from src/brand/logo.mjs. Do not edit. */\n' +
    '.xtxp-logo{--xl-x:var(--sl-color-white);--xl-t:#ff5436;--xl-p:#7c8396}\n' +
    ':root[data-theme="light"] .xtxp-logo{--xl-t:#ff5436;--xl-p:#8a91a3}\n' +
    logoCss('.xtxp-logo').replace(/\}(?=[.@:])/g, '}\n') + '\n'
);
